# 1. Load Dataset
def load_formal_jobs(path):
    df = pd.read_csv(path)
    out = pd.DataFrame()
    out["job_id"] = ["FML" + str(i + 1).zfill(4) for i in range(len(df))]
    out["judul"] = df["title"].fillna("")

    # Gabungan teks untuk TF-IDF
    out["deskripsi"] = (
        df["title"].fillna("") + ". " +
        df["requirement"].fillna("") + ". " +
        df["description"].fillna("") + ". " +
        df["qualification"].fillna("")
    )
    out["kategori"] = df["type_of_work"].fillna(df["job_level"]).fillna("")
    out["sumber"] = "Formal"
    out["company"] = df.get("company", "")
    out["link"] = df.get("link", "")
    return out


def load_informal_jobs(path):
    df = pd.read_csv(path)
    out = pd.DataFrame()
    out["job_id"] = df["job_id"]
    out["judul"] = df["judul_pekerjaan"]
    out["deskripsi"] = df["judul_pekerjaan"] + ". " + df["deskripsi"]
    out["kategori"] = df["kategori_skill"]
    out["sumber"] = "Informal"
    out["company"] = "Perorangan/UMKM"
    out["link"] = ""
    return out


def load_workers(path):
    df = pd.read_csv(path)
    out = pd.DataFrame()
    out["worker_id"] = df["worker_id"]
    out["nama"] = df["name"]
    out["jenis_kelamin"] = df["gender"]
    out["skill_text"] = df["skills"].fillna("")
    return out


def build_datasets(formal_path, informal_path, worker_path, out_dir="data"):
    os.makedirs(out_dir, exist_ok=True)

    formal = load_formal_jobs(formal_path)
    informal = load_informal_jobs(informal_path)
    workers = load_workers(worker_path)

    all_jobs = pd.concat([formal, informal], ignore_index=True)
    all_jobs = all_jobs[all_jobs["judul"].str.strip() != ""]
    all_jobs = all_jobs.drop_duplicates(subset=["judul", "deskripsi"]).reset_index(drop=True)

    workers = workers[workers["skill_text"].str.strip() != ""]
    workers = workers.drop_duplicates(subset=["nama", "skill_text"]).reset_index(drop=True)

    all_jobs.to_csv(f"{out_dir}/all_jobs.csv", index=False)
    workers.to_csv(f"{out_dir}/all_workers.csv", index=False)

    print(f"[load_data] Total job: {len(all_jobs)}")
    print(f"[load_data] Total worker: {len(workers)}")
    return all_jobs, workers

