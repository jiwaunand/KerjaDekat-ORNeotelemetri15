import numpy as np

def evaluate_recommender(recommender_system, sample_size=50, top_n=10):
    """
    Menghitung rata-rata skill_score untuk top_n rekomendasi
    dari sampel worker acak.
    """
    workers_sample = recommender_system.workers.sample(
        n=min(sample_size, len(recommender_system.workers)),
        random_state=42
    )

    all_top_scores = []

    for wid in workers_sample["worker_id"]:
        rec_df = recommender_system.recommend_for_worker(wid, top_n=top_n)
        mean_score = rec_df["skill_score"].mean()
        all_top_scores.append(mean_score)

    overall_avg = np.mean(all_top_scores)
    print(f"=== HASIL EVALUASI MODEL ===")
    print(f"Jumlah sampel worker  : {len(workers_sample)}")
    print(f"Top-N Rekomendasi     : {top_n}")
    print(f"Rata-rata Skill Score : {overall_avg:.4f}")
    return overall_avg

