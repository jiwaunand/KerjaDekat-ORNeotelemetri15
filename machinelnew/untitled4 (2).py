def clean_text(text):
    if not isinstance(text, str):
        return ""
    text = text.lower()
    text = re.sub(r"[^a-z0-9\s]", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    tokens = [w for w in text.split() if w not in STOPWORDS_ID and len(w) > 1]
    return " ".join(tokens)


def build_job_corpus(all_jobs_df):
    combined = (
        all_jobs_df["judul"].fillna("") + " " +
        all_jobs_df["kategori"].fillna("") + " " +
        all_jobs_df["deskripsi"].fillna("")
    )
    return combined.apply(clean_text)


def build_worker_corpus(workers_df):
    return workers_df["skill_text"].fillna("").apply(clean_text)

