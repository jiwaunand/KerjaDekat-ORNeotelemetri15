# 3. TF IDF

class KerjaDekatRecommender:
    def __init__(self, all_jobs_df, workers_df):
        self.jobs = all_jobs_df.reset_index(drop=True)
        self.workers = workers_df.reset_index(drop=True)

        self.job_corpus = build_job_corpus(self.jobs)
        self.worker_corpus = build_worker_corpus(self.workers)

        self.vectorizer = TfidfVectorizer(
        ngram_range=(1, 2),
        max_features=5000,
        sublinear_tf=True,
        max_df=0.3
        )

        combined_corpus = pd.concat([self.job_corpus, self.worker_corpus])
        self.vectorizer.fit(combined_corpus)

        self.job_vectors = self.vectorizer.transform(self.job_corpus)
        self.worker_vectors = self.vectorizer.transform(self.worker_corpus)

    def recommend_for_worker(self, worker_id, top_n=10):
        idx_list = self.workers.index[self.workers["worker_id"] == worker_id].tolist()
        if not idx_list:
            raise ValueError(f"worker_id '{worker_id}' tidak ditemukan")
        w_idx = idx_list[0]

        # Hitung kemiripan skill
        skill_scores = cosine_similarity(
            self.worker_vectors[w_idx], self.job_vectors
        ).flatten()

        result = self.jobs.copy()
        result["skill_score"] = (skill_scores * 100).round(2)

        top_jobs = result.sort_values("skill_score", ascending=False).head(top_n).reset_index(drop=True)

        cols = ["job_id", "judul", "sumber", "kategori", "skill_score"]
        return top_jobs[cols]

    def predict_new_worker(self, skill_text, top_n=10):
        teks_bersih = clean_text(skill_text)
        vector_baru = self.vectorizer.transform([teks_bersih])
        skill_scores = cosine_similarity(
            vector_baru, self.job_vectors
        ).flatten()

        result = self.jobs.copy()
        result["skill_score"] = (skill_scores * 100).round(2)
        top_jobs = (
            result.sort_values("skill_score", ascending=False)
            .head(top_n)
            .reset_index(drop=True)
        )

        cols = ["job_id", "judul", "sumber", "kategori", "skill_score"]
        return top_jobs[cols]

    def predict_new_job(self, judul, deskripsi, top_n=10):
        """Untuk job baru yang belum ada di database."""
        teks_bersih = clean_text(judul + " " + deskripsi)
        vector_baru = self.vectorizer.transform([teks_bersih])
        skill_scores = cosine_similarity(
            vector_baru, self.worker_vectors
        ).flatten()

        result = self.workers.copy()
        result["skill_score"] = (skill_scores * 100).round(2)
        top_workers = (
            result.sort_values("skill_score", ascending=False)
            .head(top_n)
            .reset_index(drop=True)
        )

        cols = ["worker_id", "nama", "skill_score"]
        return top_workers[cols]

    def get_top_keywords(self, top_n=20):
        feature_names = self.vectorizer.get_feature_names_out()
        sums = np.asarray(self.job_vectors.sum(axis=0)).flatten()
        top_indices = sums.argsort()[::-1][:top_n]
        return [(feature_names[i], round(sums[i], 2)) for i in top_indices]

