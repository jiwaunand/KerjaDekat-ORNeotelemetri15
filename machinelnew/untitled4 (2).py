def evaluate_precision_at_k(recommender_system, sample_size=50, top_n=10, threshold=0.05):
    workers_sample = recommender_system.workers.sample(
        n=min(sample_size, len(recommender_system.workers)),
        random_state=42
    )

    precision_list = []

    for wid in workers_sample["worker_id"]:
        rec_df = recommender_system.recommend_for_worker(wid, top_n=top_n)
        # Hitung berapa banyak job dari Top-N yang skornya di atas threshold
        relevant_jobs = (rec_df["skill_score"] >= threshold).sum()
        precision = relevant_jobs / top_n
        precision_list.append(precision)

    avg_precision = np.mean(precision_list)
    print(f"=== EVALUASI PRECISION@{top_n} ===")
    print(f"Threshold Skor Relevan : {threshold}")
    print(f"Mean Precision@{top_n}    : {avg_precision * 100:.2f}%")
    return avg_precision

